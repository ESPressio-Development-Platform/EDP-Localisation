from __future__ import annotations

import json
import os
import fcntl
from unittest import mock
import tempfile
import unittest
from pathlib import Path

import test_toolchain
from edp_localisation.common import ToolError
from edp_localisation.cli import main
from edp_localisation.compiler import compile_generated_set
from edp_localisation.historical_archive import (
    archive_generated_family, open_historical_family,
)


class HistoricalArchiveTests(unittest.TestCase):
    def test_publish_reopen_and_reject_modified_bytes(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            source, platform, schema = test_toolchain.ToolchainTests().make_fixture(root)
            generated = root / "generated"
            archive = root / "history"
            compile_generated_set(source, platform, [schema], generated, "Fixture::History")
            first = archive_generated_family(generated, archive)
            self.assertEqual(first["status"], "Archived")
            self.assertEqual(archive_generated_family(generated, archive)["status"], "AlreadyArchived")
            self.assertEqual(main([
                "archive-family", "--generated", str(generated),
                "--archive", str(archive),
            ]), 0)
            self.assertEqual(main([
                "verify-archived-family", "--archive", str(archive),
                "--fingerprint", first["fingerprint"], "--digest", first["digest"],
            ]), 0)
            family = open_historical_family(archive, first["fingerprint"], digest=first["digest"])
            self.assertEqual(family.fingerprint.hex().upper(), first["fingerprint"])
            self.assertEqual(family.resolve_string("de", 1, 0, 5).status, "Success")
            self.assertEqual(family.resolve_string("de", 1, 0, 5).value, "Grüße")

            # The archived generated bytes survive deletion of the source set.
            for path in sorted(generated.rglob("*"), reverse=True):
                if path.is_file():
                    path.unlink()
            self.assertEqual(
                open_historical_family(archive, first["fingerprint"])
                .resolve_string("de", 1, 0, 5).value,
                "Grüße",
            )
            family_path = archive / "families" / first["digest"]
            (family_path / "packs" / "de.edploc").write_bytes(b"EDPL-corrupt")
            with self.assertRaises(ToolError):
                open_historical_family(archive, first["fingerprint"])
            with self.assertRaises(ToolError):
                archive_generated_family(family_path, archive)

    def test_multiple_versions_are_addressed_by_semantic_fingerprint(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            source, platform, schema = test_toolchain.ToolchainTests().make_fixture(root)
            archive = root / "history"
            old = root / "old"
            compile_generated_set(source, platform, [schema], old, "Fixture::History")
            first = archive_generated_family(old, archive)
            strings = source / "en-GB" / "strings.json"
            value = json.loads(strings.read_text("utf-8"))
            value["domains"]["1"]["subDomains"]["0"]["strings"]["3"] = "Changed historical text"
            test_toolchain.write_json(strings, value)
            current = root / "current"
            compile_generated_set(source, platform, [schema], current, "Fixture::History")
            second = archive_generated_family(current, archive)
            self.assertNotEqual(first["fingerprint"], second["fingerprint"])
            self.assertEqual(
                open_historical_family(archive, first["fingerprint"])
                .resolve_string("en-GB", 1, 0, 3).value,
                "Hello",
            )
            self.assertEqual(
                open_historical_family(archive, second["fingerprint"])
                .resolve_string("en-GB", 1, 0, 3).value,
                "Changed historical text",
            )
            with self.assertRaises(ToolError):
                open_historical_family(archive, "a" * 32)
            with self.assertRaises(ToolError):
                open_historical_family(archive, "0" * 32)
            with self.assertRaises(ToolError):
                open_historical_family(archive, first["fingerprint"], digest=second["digest"])

    def test_concurrent_publisher_fails_closed_without_waiting(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            source, platform, schema = test_toolchain.ToolchainTests().make_fixture(root)
            generated = root / "generated"
            compile_generated_set(source, platform, [schema], generated, "Fixture::History")
            archive = root / "history"
            # Create the durable lock inode by first successful publication.
            initial = archive_generated_family(generated, archive)
            descriptor = os.open(archive / ".publisher.lock", os.O_RDWR)
            try:
                fcntl.flock(descriptor, fcntl.LOCK_EX | fcntl.LOCK_NB)
                with self.assertRaisesRegex(ToolError, "another historical publisher is active"):
                    archive_generated_family(generated, archive)
            finally:
                fcntl.flock(descriptor, fcntl.LOCK_UN)
                os.close(descriptor)
            self.assertEqual(
                archive_generated_family(generated, archive)["status"],
                "AlreadyArchived",
            )
            self.assertTrue(
                open_historical_family(archive, initial["fingerprint"])
                .resolve_string("en-GB", 1, 0, 3).status == "Success"
            )

    def test_pre_publish_failure_cannot_expose_partial_family(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            source, platform, schema = test_toolchain.ToolchainTests().make_fixture(root)
            generated = root / "generated"
            archive = root / "history"
            compile_generated_set(source, platform, [schema], generated, "Fixture::History")
            with mock.patch("edp_localisation.historical_archive.os.rename",
                            side_effect=OSError("injected interrupted rename")):
                with self.assertRaisesRegex(OSError, "interrupted rename"):
                    archive_generated_family(generated, archive)
            self.assertFalse(list((archive / "families").iterdir()))
            result = archive_generated_family(generated, archive)
            self.assertEqual(result["status"], "Archived")
            self.assertTrue(
                open_historical_family(archive, result["fingerprint"])
                .resolve_string("en-GB", 1, 0, 3).status == "Success"
            )

    def test_fsyncs_all_files_and_directory_metadata(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            source, platform, schema = test_toolchain.ToolchainTests().make_fixture(root)
            generated = root / "generated"
            archive = root / "history"
            compile_generated_set(source, platform, [schema], generated, "Fixture::History")
            with mock.patch("edp_localisation.historical_archive.os.fsync",
                            wraps=os.fsync) as sync:
                result = archive_generated_family(generated, archive)
                files_count = len(list((archive / "families" / result["digest"]).rglob("*")))
                # Source manifest, every output, stage dirs, final directory and lock inode.
                self.assertGreaterEqual(sync.call_count, files_count + 3)
            self.assertEqual(
                open_historical_family(archive, result["fingerprint"]).fingerprint.hex().upper(),
                result["fingerprint"],
            )

    def test_symlinks_are_fail_closed(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            source, platform, schema = test_toolchain.ToolchainTests().make_fixture(root)
            generated = root / "generated"
            compile_generated_set(source, platform, [schema], generated, "Fixture::History")
            (generated / "alias").symlink_to(generated / "packs", target_is_directory=True)
            with self.assertRaises(ToolError):
                archive_generated_family(generated, root / "history")

if __name__ == "__main__":
    unittest.main()
